// Bundles src/ into plugin/plugin.js: the one self-contained ES module Buzz
// loads, exporting `inject` and `apply`. React and every host service come
// from `ctx`, so nothing is external. `node scripts/build.mjs [outfile]`.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

/** esbuild options for the plugin bundle; dev/validate.mjs rebuilds with them. */
export const options = {
  absWorkingDir: root,
  entryPoints: ["src/main.js"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  charset: "utf8",
  legalComments: "none",
  banner: {
    js: "// Generated by `npm run build` (esbuild) from src/; edit src/, not this file.\n// Marmot chats for Buzz: https://github.com/januszgrze/buzz-marmot-plugin",
  },
};

/** Builds the bundle into `outfile` (relative to the repository). */
export async function buildPlugin(outfile = "plugin/plugin.js") {
  await build({ ...options, outfile, logLevel: "warning" });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await buildPlugin(process.argv[2]);
  console.log(`built ${process.argv[2] ?? "plugin/plugin.js"}`);
}
